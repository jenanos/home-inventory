/** Characters that end a word: anything that is not a letter or digit. */
const NOT_WORD = "[^a-z0-9æøåäöüéè]"

/**
 * One keyword as a regular expression source. Both JavaScript and PostgreSQL
 * read it the same way: no `\b` (neither knows æ, ø and å are letters) and no
 * lookaround, only plain groups.
 */
export function keywordPattern(keyword: string) {
  let source = keyword
  let prefix = ""
  let suffix = ""
  if (source.startsWith("^")) {
    source = source.slice(1)
    prefix = `(^|${NOT_WORD})`
  }
  if (source.endsWith("$")) {
    source = source.slice(0, -1)
    suffix = `($|${NOT_WORD})`
  }
  return `${prefix}${source}${suffix}`
}

/** All of a category's keywords as one alternation. */
export function categoryPattern(keywords: readonly string[]) {
  return keywords.map((keyword) => `(${keywordPattern(keyword)})`).join("|")
}

const COMPILED = CATEGORY_KEYWORDS.map(
  ([category, keywords]) =>
    [category, new RegExp(categoryPattern(keywords))] as const
)

/** Lower case with single spaces, as the keywords are written. */
export function normalizeForCategory(text: string) {
  return text.trim().replace(/\s+/g, " ").toLocaleLowerCase("nb-NO")
}

/** The category a name points to, or null when no keyword matches. */
export function matchPackingCategory(
  name: string
): PackingCategoryValue | null {
  const text = normalizeForCategory(name)
  for (const [category, pattern] of COMPILED) {
    if (pattern.test(text)) return category
  }
  return null
}

/**
 * The category for a new thing: from its own name, else from the hints in
 * order (the bundle's name: everything in "Toalettsaker" is a toiletry), else
 * OTHER. A guess; the user or an MCP client can always set it.
 */
export function guessPackingCategory(
  name: string,
  ...hints: Array<string | null | undefined>
): PackingCategoryValue {
  for (const text of [name, ...hints]) {
    if (!text) continue
    const category = matchPackingCategory(text)
    if (category) return category
  }
  return "OTHER"
}
