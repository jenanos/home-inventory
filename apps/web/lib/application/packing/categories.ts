/*
 * Packing categories (ADR 0018): what kind of thing an item is, so a list can
 * be shown by category instead of by bundle. Pure, so the web page can guess a
 * category with the same rule the write services use.
 */

/** In display order: the order the sections appear in on the list page. */
export const PACKING_CATEGORIES = [
  "CLOTHING",
  "TOILETRIES",
  "HEALTH",
  "ELECTRONICS",
  "DOCUMENTS",
  "KIDS",
  "FOOD",
  "OUTDOOR",
  "HOME",
  "LEISURE",
  "OTHER",
] as const

export type PackingCategoryValue = (typeof PACKING_CATEGORIES)[number]

export function isPackingCategory(
  value: unknown
): value is PackingCategoryValue {
  return (PACKING_CATEGORIES as readonly unknown[]).includes(value)
}

/** Sorts categories in display order. */
export function compareCategories(
  a: PackingCategoryValue,
  b: PackingCategoryValue
) {
  return PACKING_CATEGORIES.indexOf(a) - PACKING_CATEGORIES.indexOf(b)
}

